SELECT 
    DATE::DATE AS DATE_DAY,
    TRIM(CUSTOMER_ID::VARCHAR) AS ACCOUNT_ID,
    TRIM(CAMPAIGN_ID::VARCHAR) AS CAMPAIGN_ID,
    LOWER(TRIM(CAMPAIGN_NAME::VARCHAR)) AS CAMPAIGN_NAME,
    LOWER(TRIM(CAMPAIGN_TYPE::VARCHAR)) AS CAMPAIGN_TYPE,
    IMPRESSIONS::INT AS IMPRESSIONS,
    CLICKS::INT AS CLICKS,
    COST_MICROS::BIGINT AS COST_MICROS,
    ROUND(COST_MICROS / 1000000.0, 2) AS AMOUNT_SPENT,
    CONVERSIONS::INT AS CONVERSIONS,
    CONVERSIONS_VALUE::NUMERIC(18, 2) AS CONVERSIONS_VALUE
FROM {{ source('ads_source', 'GOOGLE_ADS_DAILY') }}