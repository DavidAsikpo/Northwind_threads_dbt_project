SELECT
    DATE::DATE AS DATE_DAY,
    UPPER(TRIM(ACCOUNT_ID::VARCHAR)) AS ACCOUNT_ID,
    TRIM(CAMPAIGN_ID::VARCHAR) AS CAMPAIGN_ID,
    LOWER(TRIM(CAMPAIGN_NAME::VARCHAR)) AS CAMPAIGN_NAME,
    LOWER(TRIM(OBJECTIVE::VARCHAR)) AS OBJECTIVE,
    IMPRESSIONS::INT AS IMPRESSIONS,
    REACH::INT AS REACH,
    LINK_CLICKS::INT AS LINK_CLICKS,
    ROUND(SPEND::NUMERIC(18, 2), 2) AS AMOUNT_SPENT,
    UPPER(TRIM(CURRENCY::VARCHAR)) AS CURRENCY,
    PURCHASES::INT AS PURCHASES,
    PURCHASE_VALUE::NUMERIC(18, 2) AS PURCHASE_VALUE
FROM {{ source('ads_source', 'META_ADS_DAILY') }}