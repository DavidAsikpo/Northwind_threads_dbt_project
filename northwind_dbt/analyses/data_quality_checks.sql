
--- CHECK FOR DUPLICATES IN ADS.GOOGLE_ADS_DAILY
WITH BASE AS
(SELECT DATE,
       CAMPAIGN_ID,
       ROW_NUMBER() OVER (PARTITION BY DATE, CAMPAIGN_ID ORDER BY DATE) AS occurence 
FROM {{ source('ads_source', 'GOOGLE_ADS_DAILY') }})
SELECT * FROM BASE 
WHERE occurence = 2

